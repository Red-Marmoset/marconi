#!/usr/bin/env bash
# Build wrapper for macOS/Linux: sets UNA_ENGINE_PATH and invokes the engine's
# BuildTool on a Project.json from the Marconi root (so output lands in ./Build).
#
# Usage:
#   ./Build.sh [Project.json] [BuildTool args...]
#   ./Build.sh                                   # the app, Release
#   ./Build.sh Tests/MarconiCoreTest/Project.json -config Debug

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
: "${UNA_ENGINE_PATH:=$SCRIPT_DIR/../engine}"
export UNA_ENGINE_PATH

PROJECT="Project.json"
if [[ $# -gt 0 && "$1" == *.json ]]; then
    PROJECT="$1"
    shift
fi

BUILDTOOL=""
for cfg in Release MinSizeRel Debug Bootstrap; do
    if [[ -x "$UNA_ENGINE_PATH/Build/BuildTool/$cfg/BuildTool" ]]; then
        BUILDTOOL="$UNA_ENGINE_PATH/Build/BuildTool/$cfg/BuildTool"
        break
    fi
done

if [[ -z "$BUILDTOOL" ]]; then
    echo "[Build.sh] BuildTool not found under $UNA_ENGINE_PATH/Build/BuildTool/."
    echo "[Build.sh] Bootstrap it first: cd $UNA_ENGINE_PATH && ./BootstrapBuildTool.sh"
    exit 1
fi

# Version: MAJOR.MINOR.PATCH from Project.json plus a revision, the number of commits in HEAD's history (the first
# commit is 1). Written to a generated header that Version.cpp includes. Build.ps1 does the same.
update_build_version() {
    local base major minor patch revision commit version header path
    base="$(sed -n 's/^[[:space:]]*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$SCRIPT_DIR/Project.json" | head -n 1)"
    if [[ ! "$base" =~ ^([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
        echo "[Build.sh] Project.json version '$base' must be MAJOR.MINOR.PATCH."
        exit 1
    fi
    major="${BASH_REMATCH[1]}"
    minor="${BASH_REMATCH[2]}"
    patch="${BASH_REMATCH[3]}"

    revision=0
    commit=unknown
    if revision="$(git -C "$SCRIPT_DIR" rev-list --count HEAD 2>/dev/null)"; then
        commit="$(git -C "$SCRIPT_DIR" rev-parse --short=7 HEAD)"
        if [[ "$(git -C "$SCRIPT_DIR" rev-parse --is-shallow-repository)" == "true" ]]; then
            echo "[Build.sh] WARNING: shallow clone; revision $revision undercounts the history."
        fi
    else
        revision=0
        echo "[Build.sh] WARNING: no git history found; building with revision 0."
    fi

    version="$major.$minor.$patch.$revision"
    header="// Generated by Build.ps1 / Build.sh from Project.json and the git history. Do not edit or commit.
// Included by Version.cpp and by MarconiUI/Marconi.rc, so it must stay plain enough for rc.exe.

#ifndef MARCONI_BUILD_VERSION_H
#define MARCONI_BUILD_VERSION_H

#define MARCONI_VERSION_MAJOR $major
#define MARCONI_VERSION_MINOR $minor
#define MARCONI_VERSION_PATCH $patch
#define MARCONI_VERSION_REVISION $revision
#define MARCONI_VERSION_STRING \"$version\"
#define MARCONI_VERSION_COMMIT \"$commit\"

#endif"

    # Only rewrite on change, so an unchanged version doesn't trigger rebuilds.
    path="$SCRIPT_DIR/Modules/MarconiCore/BuildVersion.h"
    if [[ ! -f "$path" || "$(cat "$path")" != "$header" ]]; then
        printf '%s\n' "$header" > "$path"
    fi
    echo "[Build.sh] Version=$version ($commit)"
}

update_build_version

JOBS="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"

# Default to Release unless the caller passed -config.
CONFIG_ARGS=(-config Release)
for arg in "$@"; do
    if [[ "$arg" == "-config" ]]; then
        CONFIG_ARGS=()
    fi
done

echo "[Build.sh] UNA_ENGINE_PATH=$UNA_ENGINE_PATH"
echo "[Build.sh] BuildTool=$BUILDTOOL"
echo "[Build.sh] Project=$PROJECT"

cd "$SCRIPT_DIR"
exec "$BUILDTOOL" "$PROJECT" "${CONFIG_ARGS[@]}" -j "$JOBS" "$@"
